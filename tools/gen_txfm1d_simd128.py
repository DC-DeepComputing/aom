#!/usr/bin/env python3
"""Generates SIMD128 versions of libaom's 1D transforms.

  inv: av1/common/av1_inv_txfm1d.c -> av1/common/wasm/av1_inv_txfm1d_simd128.inc
  fwd: av1/encoder/av1_fwd_txfm1d.c -> av1/encoder/wasm/av1_fwd_txfm1d_simd128.inc

Each scalar 1D transform is rewritten to operate on v128_t (i32x4)
values, so one call transforms 4 independent rows (or columns) at once. The
arithmetic is unchanged (32-bit wrapping, which libaom documents as exact for
conformant streams; see half_btf() in av1_txfm.h), so results are bit-exact
with the C code. Functions with irregular structure or 64-bit intermediates
(iadst4/fadst4, identity) are hand-written in the including .c file instead.

usage: gen_txfm1d_simd128.py <libaom-root> {inv,fwd}
Then run clang-format -i on the output.
"""
import re
import sys

ROOT, KIND = sys.argv[1], sys.argv[2]
# 64-point transforms fall back to C, so the 64-point DCTs are intentionally
# not generated.
if KIND == 'inv':
  SRC = f'{ROOT}/av1/common/av1_inv_txfm1d.c'
  OUT = f'{ROOT}/av1/common/wasm/av1_inv_txfm1d_simd128.inc'
  FUNCS = ['idct4', 'idct8', 'idct16', 'idct32', 'iadst8', 'iadst16']
else:
  SRC = f'{ROOT}/av1/encoder/av1_fwd_txfm1d.c'
  OUT = f'{ROOT}/av1/encoder/wasm/av1_fwd_txfm1d_simd128.inc'
  FUNCS = ['fdct4', 'fdct8', 'fdct16', 'fdct32', 'fadst8', 'fadst16']

src = open(SRC).read()
out = ['/*',
       ' * Copyright (c) 2026, Alliance for Open Media. All rights reserved.',
       ' *',
       ' * This source code is subject to the terms of the BSD 2 Clause License and',
       ' * the Alliance for Open Media Patent License 1.0. If the BSD 2 Clause License',
       ' * was not distributed with this source code in the LICENSE file, you can',
       ' * obtain it at www.aomedia.org/license/software. If the Alliance for Open',
       ' * Media Patent License 1.0 was not distributed with this source code in the',
       ' * PATENTS file, you can obtain it at www.aomedia.org/license/patent.',
       ' */',
       '',
       '// GENERATED by tools/gen_txfm1d_simd128.py from',
       f'// {SRC[len(ROOT) + 1:]} (then clang-format). Do not edit;',
       '// regenerate instead.',
       '// Requires half_btf_v()' + (' and clamp_v()' if KIND == 'inv' else '') +
       ' to be defined by the includer.',
       '']

for name in FUNCS:
  m = re.search(r'void av1_%s\(const int32_t \*input, int32_t \*output, '
                r'int8_t cos_bit,\s*const int8_t \*stage_range\) \{\n' % name,
                src)
  assert m, name
  # Function body: up to the matching closing brace at column 0.
  end = src.index('\n}\n', m.end())
  body = '\n' + src[m.end():end]
  body = body.replace('int32_t *bf0, *bf1;', 'v128_t *bf0, *bf1;')
  body = re.sub(r'int32_t step\[(\d+)\];', r'v128_t step[\1];', body)
  body = re.sub(r'\n\s*av1_range_check_buf\([^;]*\);', '', body)
  body = re.sub(r'\n\s*const int32_t size = \d+;', '', body)
  body = body.replace('half_btf(', 'half_btf_v(')
  body = body.replace('clamp_value(', 'clamp_v(')
  if 'stage_range[' not in body:
    # The forward transforms only used `stage` for the removed range checks.
    body = re.sub(r'\n\s*int32_t stage = 0;', '', body)
    body = re.sub(r'\n\s*stage\+\+;', '', body)
    body = '\n  (void)stage_range;' + body
  # Anything still scalar-int32 on data paths would be a converter bug.
  for line in body.split('\n'):
    if re.search(r'\bint32_t\b', line) and 'cospi' not in line and \
       'stage = 0' not in line:
      raise SystemExit(f'unconverted declaration in {name}: {line}')
  out.append(f'static void {name}_simd128(const v128_t *input, v128_t *output,')
  out.append('                            int8_t cos_bit,')
  out.append('                            const int8_t *stage_range) {')
  out.append(body.strip('\n'))
  out.append('}')
  out.append('')

open(OUT, 'w').write('\n'.join(out))
print(f'wrote {OUT}')
